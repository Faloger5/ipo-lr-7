# Создаём список книг (пример данных)
books = [
    {"title": "Война и мир", "author": "Лев Толстой", "year": 1869},
    {"title": "Дом в котором", "author": "Мариам Петросян", "year": 2009},
    {"title": "Мастер и Маргарита", "author": "Михаил Булгаков", "year": 1967},
    {"title": "Преступление и наказание", "author": "Фёдор Достоевский", "year": 1866},
    {"title": "Сто лет одиночества", "author": "Габриэль Гарсиа Маркес", "year": 1967},
]

# Вывод по образцу. Нумерация начинается с 1.
for idx, book in enumerate(books, start=1):
    print(f" ---------------------- Книга {idx} -----------------------")
    print(f" Название: {book['title']}, Автор: {book['author']},")
    year_str = str(book['year'])
    dashes_left = "-------------------------"  # 25 дефисов слева
    dashes_right = "-------------------------"  # 25 дефисов справа
    # Строка с годом обрамляется дефисами, как в примере.
    print(f" {dashes_left}{year_str}{dashes_right}")
    print()

